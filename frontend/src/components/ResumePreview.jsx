/* ───── Shared helpers ───── */
function Section({ title, children, font }) {
  let fontFamily = 'Arial, sans-serif';
  if (font === 'times') fontFamily = '"Times New Roman", Times, serif';
  if (font === 'calibri') fontFamily = 'Calibri, sans-serif';

  return (
    <div className="mb-5 break-inside-avoid" style={{ fontFamily }}>
      <h2 className="uppercase tracking-wider mb-2 pb-1 text-black" style={{ fontSize: '12pt', fontWeight: 'bold', borderBottom: '1px solid black', margin: 0 }}>
        {title}
      </h2>
      {children}
    </div>
  );
}
