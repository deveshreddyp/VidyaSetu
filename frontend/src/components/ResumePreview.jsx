import React, { forwardRef } from 'react';

const ResumePreview = forwardRef(({ data, template }, ref) => {
  const certs = (data.certifications || '').split('\n').filter(Boolean);
  const achievements = (data.achievements || '').split('\n').filter(Boolean);

  if (template === 'cmrit') return <CMRITTemplate ref={ref} data={data} certs={certs} achievements={achievements} />;
  if (template === 'fresher') return <FresherTemplate ref={ref} data={data} certs={certs} achievements={achievements} />;
  return <ATSTemplate ref={ref} data={data} certs={certs} achievements={achievements} />;
});

ResumePreview.displayName = 'ResumePreview';
export default ResumePreview;

// Helper to parse **bold** text generated by AI
const renderText = (text) => {
  if (!text) return null;
  const parts = text.split(/(\*\*.*?\*\*)/g);
  return parts.map((part, i) => 
    part.startsWith('**') && part.endsWith('**') 
      ? <strong key={i} className="font-bold text-black">{part.slice(2, -2)}</strong> 
      : part
  );
};

